# === Настройки камеры через V4L2 (v4l2-ctl, пакет v4l-utils) ===
# Те же команды, что и руками в консоли, только при открытии камеры:
#   v4l2-ctl -d /dev/video0 -c auto_exposure=1
# Ключ — индекс камеры (как в списке камер), значение — {контрол: значение}.
# Ключа для камеры нет -> её настройки не трогаем. Контрола, которого нет
# на этой камере, будет пропущен с предупреждением в лог.
# ПОСЛЕ смены экспозиции/баланса белого обязательно пересними эталон
# (кнопка Set reference) — иначе алгоритм увидит "изменение" сам по себе.
#
# ПОРЯДОК ВАЖЕН: авторежимы (auto_exposure, white_balance_temperature_auto)
# ставятся ПЕРВЫМИ, иначе камера сразу вернёт авторежим и затрёт ручные
# экспозицию/баланс белого.
V4L2_APPLY_ON_OPEN = True
V4L2_CONTROLS = {
    0: {  # индекс камеры; для второй камеры добавь блок "1: {...}"
        # --- экспозиция -------------------------------------------------
        # Режим экспозиции (меню). У UVC-камер обычно:
        #   0 = авто, 1 = ручной (фиксируем exposure_absolute),
        #   2 = фикс выдержки/авто диафрагма, 3 = авто выдержка/ручная диафрагма.
        # Для детектора нужен 1: картинка не "прыгает" сама, PIXEL_THRESHOLD
        # перестаёт срабатывать на ровном месте.
        "auto_exposure": 1,
        # Время экспозиции в единицах V4L2, шаг = 100 мкс: 300 = 30 мс,
        # 1000 = 100 мс, 10000 = 1 с. Больше нельзя, чем длина кадра
        # (при 30 FPS кадр = 33 мс), иначе камера сама снизит FPS.
        "exposure_absolute": 300,
        # Частота сети: 0 = выкл, 1 = 50 Гц, 2 = 60 Гц, 3 = авто.
        # НЕ выключай: лампы и LED мерцают с этой частотой, и алгоритм
        # будет ловить тревогу на мерцании, а не на реальном изменении.
        "power_line_frequency": 1,
        # Разрешить камере менять FPS в авторежиме: 0 = нет (держим FPS).
        # В связке с auto_exposure = 1 смысла не имеет, но включи,
        # если случайно вернёшь автоэкспозицию.
        "exposure_auto_priority": 0,

        # --- баланс белого ------------------------------------------------
        # 0 = баланс белого вручную, 1 = автоматический. Ставим 0 ДО
        # задания температуры, иначе камера перепишет её своими.
        "white_balance_temperature_auto": 0,
        # Цветовая температура в Кельвинах: ~2800 = лампа накаливания,
        # ~4200 = нейтральный свет, ~6500 = дневной. Каждый шаг вниз
        # делает картинку теплее.
        "white_balance_temperature": 4200,

        # --- картинка -----------------------------------------------------
        # Уровень чёрного (сдвиг яркости), обычно -128..127. Низкий ->
        # темнее, высокий -> поднимает чёрную точку и жрёт детализацию.
        "brightness": 0,
        # Контраст (усиление яркости), 0 = нейтрально, больше -> резче.
        "contrast": 0,
        # Гамма: 0 = нейтрально, больше -> светлее тени, темнее света.
        # Для детектора обычно оставляют 0: меньше искажений яркости.
        "gamma": 0,
        # Насыщенность цвета: 0 = ч/б, больше -> цвета сочнее. На 64 (дефолт)
        # картинка обычно "живая". Можно поставить 0, если USE_GRAYSCALE = True:
        # цвет не участвует в сравнении, а шум по каналам уходит.
        "saturation": 64,
        # Оттенок (баланс цветов) в градусах, обычно -180..180.
        "hue": 0,
        # Резкость: подчёркивает границы, но и усиливает шум — для детектора
        # лучше 0, лишние контуры только добавляют ложных срабатываний.
        "sharpness": 0,
        # Усиление сигнала. Чем больше — тем ярче при слабом свете и тем
        # больше шума, который алгоритм считает изменением. Держи минимум,
        # на котором сцена ещё различима.
        "gain": 0,
        # Компенсация контрового света: 0 = выкл, 1 = вкл. Помогает, если
        # объект в кадре темнее фона, но может "выбелить" тёмные детали.
        "backlight_compensation": 0,

        # --- фокус (если у камеры есть) ----------------------------------
        # 1 = автофокус, 0 = ручной. Для детектора лучше автофокус: он сам
        # подстроится и не будет "прыгать" резкостью между кадрами.
        "focus_auto": 1,
        # Ручной фокус (в единицах камеры, обычно 0..255 или шаги 1/0..max).
        # Действует только при "focus_auto": 0.
        "focus_absolute": 0,
    },
}
